AUDIO_SAMPLE_RATE = 16_000
AUDIO_CHANNELS = 1

# --- Whisper / faster-whisper ---
DEFAULT_WHISPER_MODEL = "large-v3-turbo"
DEFAULT_WHISPER_DEVICE = "cuda"  # fallback на "cpu" делает transcribe.py при недоступности GPU
DEFAULT_WHISPER_COMPUTE_TYPE = "float16"
DEFAULT_LANGUAGE = "ru"

# --- Ollama / суммаризация ---
DEFAULT_OLLAMA_HOST = "http://localhost:11434"
DEFAULT_OLLAMA_MODEL = "qwen2.5:7b-instruct"
DEFAULT_SUMMARY_STYLE = "подробная"  # краткая | подробная | тезисы
OLLAMA_TIMEOUT_SECONDS = 180.0

# Ollama по умолчанию грузит модель с контекстом всего 4096 токенов, даже если
# сама модель поддерживает намного больше (у qwen2.5:7b-instruct нативный
# контекст - 32768). Это искусственное занижение, а не предел модели или GPU:
# явно запрашиваем 16384 - на RTX 5060 (8GB VRAM) это ~6.3GB, оставляет
# комфортный запас (~1.8GB). При желании можно поднять до полных 32768, но
# это почти не оставляет запаса VRAM на этой карте.
OLLAMA_NUM_CTX = 16384

# Порог (в символах), после которого транскрипт режется на части для
# map-reduce вместо суммаризации за один проход. У этой модели для русского
# языка ~2.8 символа/токен (замерено эмпирически) - при контексте 16384 и
# с запасом под промпт-инструкции и ответ модели остаётся ~15000 токенов
# под сам текст, то есть ~40000+ символов влезает целиком. Берём с запасом
# поменьше, чтобы суммаризация почти никогда не фрагментировала текст там,
# где это не обязательно (фрагментация на map-reduce теряет связность и
# суть - цельная суммаризация за один проход всегда предпочтительнее).
SUMMARY_CHUNK_CHAR_LIMIT = 24_000

# Расширения файлов, которые мы считаем "медиа" (видео или аудио) на входе.
SUPPORTED_EXTENSIONS = {
    # видео
    ".mp4", ".mkv", ".mov", ".avi", ".webm", ".flv", ".wmv", ".m4v",
    # аудио
    ".mp3", ".wav", ".m4a", ".aac", ".flac", ".ogg", ".opus", ".wma",
}
