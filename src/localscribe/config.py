"""Значения по умолчанию для всего пайплайна."""

from __future__ import annotations

# --- Аудио ---
# Whisper ожидает моно WAV 16kHz - это стандарт де-факто для ASR.
AUDIO_SAMPLE_RATE = 16_000
AUDIO_CHANNELS = 1

# --- Whisper / faster-whisper ---
DEFAULT_WHISPER_MODEL = "large-v3-turbo"
DEFAULT_WHISPER_DEVICE = "cuda"  # fallback на "cpu" делает transcribe.py при недоступности GPU
DEFAULT_WHISPER_COMPUTE_TYPE = "float16"
DEFAULT_LANGUAGE = "ru"

# VAD отсекает участки без речи до подачи в модель. Замерено на реальной
# 12-минутной записи: лишнего не теряется, а узнаваемость имён слегка растёт
# ("спасибо большое милю" -> "спасибо большое, Эмилю"). Времени не стоит.
WHISPER_VAD_FILTER = True

# initial_prompt подаётся модели как предшествующий контекст, и Whisper
# подхватывает оттуда написание имён собственных. Дефолта тут осознанно НЕТ,
# потому что замеры показали две вещи:
#   1. Нейтральная подсказка без конкретных имён не помогает, а вредит:
#      "Свияжск" 0->1, но "Иннополис" 3->0.
#   2. Подсказка помогает, только если называет реальные сущности записи,
#      и обязательно СВЯЗНЫМ ТЕКСТОМ, а не списком через запятую.
#      На одной и той же записи (large-v3-turbo, число верных распознаваний):
#        без подсказки      Свияжск=0  Иннополис=3
#        список имён        Свияжск=3  Иннополис=0   <- список ломает соседей
#        связное предложение Свияжск=3 Иннополис=3   <- так и надо
# Поэтому подсказку задаёт пользователь под конкретную запись: --hint.

# --- Ollama / суммаризация ---
DEFAULT_OLLAMA_HOST = "http://localhost:11434"
DEFAULT_OLLAMA_MODEL = "qwen3:8b"
DEFAULT_SUMMARY_STYLE = "подробная"  # краткая | подробная | тезисы
OLLAMA_TIMEOUT_SECONDS = 180.0

# Qwen3 - гибридная модель: по умолчанию она сначала "думает" в блоке <think>,
# и этот блок съедает бюджет num_predict, оставляя выжимку обрезанной или
# пустой. Для суммаризации рассуждения не нужны, глушим их явно.
# Параметр безопасно слать всем моделям: think=false обычные модели принимают
# и игнорируют (проверено на qwen2.5 и gemma3), ошибку даёт только think=true.
OLLAMA_THINK = False

# Ollama по умолчанию грузит модель с контекстом всего 4096 токенов, даже если
# сама модель поддерживает намного больше (у qwen3:8b нативный контекст -
# 32768). Это искусственное занижение раннера, а не предел модели или GPU:
# запрашиваем 16384 явно в каждом вызове.
# Размещение зависит от модели, версии Ollama и свободной памяти. При проверке
# 2026-11-10 qwen3:8b с этим окном размещалась на 80% в GPU и на 20% в CPU,
# qwen3.5:4b — целиком в GPU. Исторические 5.86GiB VRAM для qwen3 не означают,
# что вся модель помещается в GPU. См. BENCHMARK_RESULTS.md и `ollama ps`.
# Перед суммаризацией CLI освобождает Whisper; Ollama может держать LLM после ответа.
OLLAMA_NUM_CTX = 16384

# Порог (в символах), после которого транскрипт режется на части для
# map-reduce вместо суммаризации за один проход. Значение подобрано с запасом,
# чтобы суммаризация почти никогда не фрагментировала текст там, где это не
# обязательно (фрагментация на map-reduce теряет связность и суть - цельная
# суммаризация за один проход всегда предпочтительнее).
SUMMARY_CHUNK_CHAR_LIMIT = 24_000

# Расширения файлов, которые мы считаем "медиа" (видео или аудио) на входе.
SUPPORTED_EXTENSIONS = {
    # видео
    ".mp4", ".mkv", ".mov", ".avi", ".webm", ".flv", ".wmv", ".m4v",
    # аудио
    ".mp3", ".wav", ".m4a", ".aac", ".flac", ".ogg", ".opus", ".wma",
}
